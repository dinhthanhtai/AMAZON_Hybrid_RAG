from datetime import datetime
from typing import Optional, Any, List
from pydantic import BaseModel, Field


class RAGUsedContext(BaseModel):
    id: str = Field(description="ID of the item used to answer the question")
    description: str = Field(description="Short description of the item used to answer the question")
    image_url: Optional[str] = Field(default=None, description="URL of the image of the item used to answer the question")
    price: Optional[float] = Field(default=None, description="Price of the item used to answer the question")


class RAGRequest(BaseModel):
    query: str = Field(..., description="The query to search for in the RAG pipeline.")
    session_id: Optional[str] = Field(
        default=None,
        description="Session ID for conversation history memory. If omitted, a new session is created."
    )


class RAGResponse(BaseModel):
    answer: str = Field(..., description="The answer generated by the RAG pipeline.")
    request_id: str = Field(..., description="The unique identifier for the request.")
    session_id: str = Field(..., description="The session ID associated with this conversation.")
    used_contexts: List[RAGUsedContext] = Field(
        ...,
        description="List of contexts used to generate the answer."
    )


class ChatMessageResponse(BaseModel):
    id: str
    session_id: str
    role: str
    content: str
    request_id: Optional[str] = None
    used_contexts: Optional[Any] = None
    created_at: datetime

    class Config:
        from_attributes = True


class SessionSummaryResponse(BaseModel):
    id: str
    title: Optional[str] = None
    created_at: datetime
    updated_at: datetime

    class Config:
        from_attributes = True


class SessionDetailResponse(BaseModel):
    id: str
    title: Optional[str] = None
    created_at: datetime
    updated_at: datetime
    messages: List[ChatMessageResponse] = []

    class Config:
        from_attributes = True
